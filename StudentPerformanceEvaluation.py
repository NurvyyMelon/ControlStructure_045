percentage = float(input("Masukkan persentase: "))
if percentage >= 90:
    print("Performance Yang Sangat Bagus")
elif percentage >= 80:
    print("Performance Yang Bagus")
elif percentage >= 70:
    print("Performance Yang Cukup")
elif percentage >= 60:
    print("Performance Yang Kurang")
else:
    print("Performance Yang Perlu Ditingkatkan")